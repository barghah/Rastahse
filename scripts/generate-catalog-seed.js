/**
 * Generates supabase/migrations/20241014_catalog_seed.sql from content/products.json.
 * Usage: node scripts/generate-catalog-seed.js
 *
 * The resulting SQL (1) extends db_products with the full catalogue fields,
 * (2) deletes the existing db_products rows, and (3) inserts every catalogue
 * product with stock = 2.
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const { products } = JSON.parse(
  fs.readFileSync(path.join(root, "content", "products.json"), "utf8")
);

const STOCK = 2;
const q = (v) => (v === undefined || v === null ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (a) => `ARRAY[${a.map(q).join(", ")}]::text[]`;

const seenSku = new Set();
const rows = products.map((p) => {
  let sku = p.variants?.find((v) => v.sku)?.sku || p.id.toUpperCase();
  if (seenSku.has(sku)) sku = `${sku}-${p.id.toUpperCase()}`;
  seenSku.add(sku);

  const variants = (p.variants ?? []).map((v) => ({ ...v, stock: STOCK }));

  return `(${[
    q(sku),
    q(p.name),
    q(p.slug),
    q(p.categorySlug),
    Math.round(p.price),
    STOCK,
    q(p.description),
    arr(p.tags ?? []),
    json(p.images ?? []),
    p.visible === false ? "false" : "true",
    q(p.story),
    q(p.curatorNote),
    p.comparePrice != null ? Math.round(p.comparePrice) : "NULL",
    q(p.origin),
    json(variants),
    p.curated ? "true" : "false",
    p.curatedOrder != null ? p.curatedOrder : "NULL",
    p.oneOfOne ? "true" : "false",
    q(p.createdAt),
  ].join(", ")})`;
});

const sql = `-- ─────────────────────────────────────────────────────────────────────────────
-- Migration: move the full catalogue into db_products (stock = ${STOCK} each)
-- Generated by scripts/generate-catalog-seed.js — run in Supabase SQL Editor.
-- WARNING: deletes ALL existing rows in db_products first.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE public.db_products ADD COLUMN IF NOT EXISTS story         text;
ALTER TABLE public.db_products ADD COLUMN IF NOT EXISTS curator_note  text;
ALTER TABLE public.db_products ADD COLUMN IF NOT EXISTS compare_price integer;
ALTER TABLE public.db_products ADD COLUMN IF NOT EXISTS origin        text;
ALTER TABLE public.db_products ADD COLUMN IF NOT EXISTS variants      jsonb NOT NULL DEFAULT '[]';
ALTER TABLE public.db_products ADD COLUMN IF NOT EXISTS curated       boolean NOT NULL DEFAULT false;
ALTER TABLE public.db_products ADD COLUMN IF NOT EXISTS curated_order integer;
ALTER TABLE public.db_products ADD COLUMN IF NOT EXISTS one_of_one    boolean NOT NULL DEFAULT false;

-- Start from a clean catalogue
DELETE FROM public.db_products;

INSERT INTO public.db_products
  (sku, title, slug, category, price, stock, description, tags, images, is_visible,
   story, curator_note, compare_price, origin, variants, curated, curated_order, one_of_one, created_at)
VALUES
${rows.join(",\n")};
`;

const out = path.join(root, "supabase", "migrations", "20241014_catalog_seed.sql");
fs.writeFileSync(out, sql);
console.log(`Wrote ${rows.length} products -> ${out}`);
